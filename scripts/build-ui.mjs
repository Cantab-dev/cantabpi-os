// Turns the view HTML into a string module the edge function imports (the deploy bundles only imported code).
// Run after editing supabase/functions/mcp/ui/list.html:  node scripts/build-ui.mjs
// The view's address carries a hash of the HTML, because hosts cache a view by its address: a changed
// view gets a new address, so claude.ai fetches it instead of drawing the old copy.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../supabase/functions/mcp/', import.meta.url)
const html = readFileSync(new URL('ui/list.html', dir), 'utf8').replace(/\r\n/g, '\n')
const hash = createHash('sha256').update(html).digest('hex').slice(0, 8)
writeFileSync(
  new URL('ui_html.ts', dir),
  '// Generated by scripts/build-ui.mjs from ui/list.html. Do not edit; edit the HTML and rerun the script.\n' +
    `export const LIST_VIEW_HASH = '${hash}'\n` +
    `export const LIST_VIEW_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`ui_html.ts written (${html.length} characters, hash ${hash})`)
