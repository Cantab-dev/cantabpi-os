// Builds supabase/functions/mcp/engagement_pkg.ts from Siniša's package in vendor/bpag (docs/live-views-status.md §8):
// the schema, the seed (with the deck's public address) and the reference validator, unchanged, as a module the MCP
// function can import. Run after any change to vendor/bpag:   node scripts/build-engagement.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const pkg = join(root, 'vendor', 'bpag')
const read = (...p) => readFileSync(join(pkg, ...p), 'utf8')
const json = (...p) => JSON.parse(read(...p))

export const DECK_URL =
  'https://etofljbxzllkucmearwl.supabase.co/storage/v1/object/public/engagement-assets/bpag/scale-up-proposal.pdf'

const schema = json('data', '_schema.json')
const tables = {}
for (const t of Object.keys(schema.tables)) tables[t] = json('data', 'seed', `${t}.json`)
for (const d of tables.deck) d.pdf_url = DECK_URL
const seed = { version: json('data', 'seed', '_version.json'), log: json('data', 'seed', '_log.json'), tables }
const demo = readdirSync(join(pkg, 'demo')).filter((f) => f.endsWith('.json')).sort()
  .map((f) => ({ file: f, request: json('demo', f) }))

// The validator is CommonJS and needs fs and path only for its file I/O and CLI, which the function never calls.
const validator = read('validator', 'validate.js').replace(/^#!.*\n/, '')

const out = `// Generated by scripts/build-engagement.mjs from vendor/bpag (Siniša's package, contract ${schema.contract_version}).
// Do not edit: change vendor/bpag or the script, then run it again.
// deno-lint-ignore-file
// @ts-nocheck

export const SCHEMA: any = ${JSON.stringify(schema)}

export const SEED: any = ${JSON.stringify(seed)}

export const DEMO: { file: string; request: Record<string, unknown> }[] = ${JSON.stringify(demo)}

const unavailable = () => { throw new Error('file I/O is not available in the MCP function') }
const module = { exports: {} }
;(function (module, exports, require) {
${validator}
})(module, module.exports, () => ({ readFileSync: unavailable, writeFileSync: unavailable, existsSync: () => false, join: (...p) => p.join('/') }))

export const validateDataset: (schema: any, data: any) => { errors: any[]; warnings: any[] } = module.exports.validateDataset
export const applyWrite: (schema: any, data: any, request: any, opts?: any) => any = module.exports.applyWrite
`
writeFileSync(join(root, 'supabase', 'functions', 'mcp', 'engagement_pkg.ts'), out)
console.log(`engagement_pkg.ts: contract ${schema.contract_version}, ${Object.keys(tables).length} tables, ${demo.length} demo steps`)
