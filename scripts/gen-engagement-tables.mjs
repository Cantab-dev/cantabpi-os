// Generates the migration that stores Siniša's package as one Postgres table per package table, in the schema
// `engagement` (docs/engagement-tables-status.md). Reads and saves still hand over the package's arrays, so the
// validator, the tools and the pages do not change. The tables carry types and keys only; the validator stays the check.
// Run after a change to vendor/bpag/data/_schema.json, with a new migration name (an applied one is never edited):
//   node scripts/gen-engagement-tables.mjs supabase/migrations/<timestamp>_<name>.sql [--move]
// --move adds the one-off copy from public.engagement_tables and its drop (the first migration only).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const schema = JSON.parse(readFileSync(join(root, 'vendor', 'bpag', 'data', '_schema.json'), 'utf8'))
const [outPath, ...flags] = process.argv.slice(2)
if (!outPath) throw new Error('usage: node scripts/gen-engagement-tables.mjs <migration.sql> [--move]')
const move = flags.includes('--move')

const OWN = ['project_id', 'profile_id', 'pos', 'meta_version', 'meta_updated_at', 'meta_updated_by', 'meta_reason']
const TYPE = {
  string: 'text', text: 'text', enum: 'text', ref: 'text', date: 'date', integer: 'integer', number: 'numeric',
  boolean: 'boolean', ref_list: 'text[]',
}
const q = (name) => `"${name.replace(/"/g, '""')}"`
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`
const names = Object.keys(schema.tables)

function table(name, def) {
  const cols = [
    'project_id uuid not null references public.engagement_datasets (project_id) on delete cascade',
    'profile_id uuid not null references public.profiles (id) on delete cascade',
    'pos integer not null',
    'id text not null',
  ]
  for (const [f, fd] of Object.entries(def.fields)) {
    if (fd.type === 'id') continue
    if (!TYPE[fd.type]) throw new Error(`${name}.${f}: no column type for ${fd.type}`)
    if (OWN.includes(f)) throw new Error(`${name}.${f}: clashes with an owner or meta column`)
    let col = `${q(f)} ${TYPE[fd.type]}`
    if (fd.type === 'enum') col += ` check (${q(f)} in (${fd.values.map(lit).join(', ')}))`
    cols.push(col)
  }
  cols.push('meta_version integer', 'meta_updated_at timestamptz', 'meta_updated_by text', 'meta_reason text',
    'primary key (project_id, id)')
  return `-- ${def.description.split('\n')[0]}
create table engagement.${q(name)} (
  ${cols.join(',\n  ')}
);
alter table engagement.${q(name)} enable row level security;
create policy "Own engagement rows: read" on engagement.${q(name)}
  for select to authenticated using ((select auth.uid()) = profile_id);
`
}

const sql = `-- Generated by scripts/gen-engagement-tables.mjs from vendor/bpag/data/_schema.json (contract ${schema.contract_version}).
-- Do not edit: change the schema or the script, then generate a new migration.
-- docs/engagement-tables-status.md: one table per package table in the schema engagement, so the data can be queried
-- with SQL. engagement_read, engagement_commit and engagement_replace keep their signatures and the package's arrays.

create schema engagement;
revoke all on schema engagement from public, anon;
grant usage on schema engagement to authenticated, service_role;

-- 1. The ${names.length} tables. Types and keys only: required fields, lengths, ranges and references stay in the validator.
${names.map((n) => table(n, schema.tables[n])).join('\n')}
revoke all on all tables in schema engagement from public, anon, authenticated;
grant select on all tables in schema engagement to authenticated;

-- 2. Helpers.
create function engagement.tables()
returns text[]
language sql
immutable
set search_path = ''
as $$
  select array[${names.map(lit).join(', ')}]
$$;

-- The package's _meta.updated_at as JavaScript writes it: UTC, milliseconds only when not zero.
create function engagement.iso(p timestamptz)
returns text
language sql
immutable
set search_path = ''
as $$
  select to_char(p at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS')
    || case when extract(microseconds from p)::bigint % 1000000 = 0 then ''
       else '.' || to_char(p at time zone 'UTC', 'MS') end || 'Z'
$$;

-- One table back as the package's array: same field names, empty fields left out, in order. As the caller (RLS).
create function engagement.get(p_project uuid, p_tbl text)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  out jsonb;
begin
  if not p_tbl = any (engagement.tables()) then
    raise exception 'invalid_parameter: unknown engagement table %', p_tbl;
  end if;
  execute format($q$
    select coalesce(jsonb_agg(
      jsonb_strip_nulls(to_jsonb(t) - array[${OWN.map(lit).join(', ')}]::text[])
        || jsonb_build_object('_meta', jsonb_strip_nulls(jsonb_build_object('version', t.meta_version,
          'updated_at', engagement.iso(t.meta_updated_at), 'updated_by', t.meta_updated_by, 'reason', t.meta_reason)))
      order by t.pos), '[]')
    from engagement.%I t where t.project_id = $1
  $q$, p_tbl) into out using p_project;
  return out;
end;
$$;

-- Replace one table's rows for a project with the package's array. Empty values ('' or null) are not stored; the
-- validator treats them alike. Called only from the save functions below.
create function engagement.put(p_profile uuid, p_project uuid, p_tbl text, p_records jsonb)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  n integer;
begin
  if not p_tbl = any (engagement.tables()) then
    raise exception 'invalid_parameter: unknown engagement table %', p_tbl;
  end if;
  if jsonb_typeof(p_records) <> 'array' then
    raise exception 'invalid_parameter: % is not an array', p_tbl;
  end if;
  execute format('delete from engagement.%I where project_id = $1', p_tbl) using p_project;
  execute format($q$
    insert into engagement.%1$I
    select (jsonb_populate_record(null::engagement.%1$I,
      (select coalesce(jsonb_object_agg(k, v), '{}') from jsonb_each(e.rec - '_meta') f(k, v)
        where v <> 'null'::jsonb and v <> '""'::jsonb)
      || jsonb_build_object('project_id', $2, 'profile_id', $1, 'pos', e.ord,
        'meta_version', e.rec -> '_meta' -> 'version', 'meta_updated_at', e.rec -> '_meta' -> 'updated_at',
        'meta_updated_by', e.rec -> '_meta' -> 'updated_by', 'meta_reason', e.rec -> '_meta' -> 'reason'))).*
    from jsonb_array_elements($3) with ordinality e(rec, ord)
  $q$, p_tbl) using p_profile, p_project, p_records;
  get diagnostics n = row_count;
  return n;
end;
$$;

revoke execute on function engagement.tables(), engagement.iso(timestamptz) from public, anon;
revoke execute on function engagement.get(uuid, text) from public, anon;
revoke execute on function engagement.put(uuid, uuid, text, jsonb) from public, anon, authenticated;
grant execute on function engagement.tables(), engagement.iso(timestamptz) to authenticated, service_role;
grant execute on function engagement.get(uuid, text) to authenticated, service_role;
grant execute on function engagement.put(uuid, uuid, text, jsonb) to service_role;

-- 3. The public functions, same signatures and output as before.
create or replace function public.engagement_read(p_project uuid, p_tables text[] default null)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  d public.engagement_datasets;
  k text;
  tabs jsonb := '{}';
begin
  select * into d from public.engagement_datasets where project_id = p_project;
  if not found then
    return jsonb_build_object('status', 'empty');
  end if;
  for k in select unnest(engagement.tables()) loop
    if p_tables is null or k = any (p_tables) then
      tabs := tabs || jsonb_build_object(k, engagement.get(p_project, k));
    end if;
  end loop;
  return jsonb_build_object('status', 'ok',
    'version', jsonb_build_object('global', d.global_version, 'tables', d.table_versions), 'tables', tabs);
end;
$$;

create or replace function public.engagement_commit(
  p_profile uuid, p_project uuid, p_expected_version integer, p_version jsonb, p_tables jsonb, p_log jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  d public.engagement_datasets;
  k text;
begin
  if not public.engagement_owns(p_profile, p_project) then
    raise exception 'not_found: project';
  end if;
  select * into d from public.engagement_datasets where project_id = p_project for update;
  if not found then
    return jsonb_build_object('status', 'empty');
  end if;
  if d.global_version <> p_expected_version then
    return jsonb_build_object('status', 'conflict',
      'version', jsonb_build_object('global', d.global_version, 'tables', d.table_versions));
  end if;
  for k in select jsonb_object_keys(p_tables) loop
    perform engagement.put(p_profile, p_project, k, p_tables -> k);
  end loop;
  update public.engagement_datasets
  set global_version = (p_version ->> 'global')::integer, table_versions = p_version -> 'tables'
  where project_id = p_project;
  insert into public.engagement_log (project_id, profile_id, version, at, agent, reason, changes)
  values (p_project, p_profile, (p_log ->> 'version')::integer, (p_log ->> 'at')::timestamptz, p_log ->> 'agent',
    p_log ->> 'reason', coalesce(p_log -> 'changes', '[]'));
  delete from public.engagement_log
  where project_id = p_project and id not in (
    select id from public.engagement_log where project_id = p_project order by version desc, id desc limit 200
  );
  return jsonb_build_object('status', 'ok');
end;
$$;

create or replace function public.engagement_replace(
  p_profile uuid, p_project uuid, p_contract text, p_version jsonb, p_tables jsonb, p_log jsonb default '[]'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  k text;
  e jsonb;
begin
  if not public.engagement_owns(p_profile, p_project) then
    raise exception 'not_found: project';
  end if;
  insert into public.engagement_datasets (project_id, profile_id, contract_version, global_version, table_versions)
  values (p_project, p_profile, p_contract, (p_version ->> 'global')::integer, p_version -> 'tables')
  on conflict (project_id) do update set contract_version = excluded.contract_version,
    global_version = excluded.global_version, table_versions = excluded.table_versions;
  for k in select unnest(engagement.tables()) loop
    perform engagement.put(p_profile, p_project, k, coalesce(p_tables -> k, '[]'));
  end loop;
  delete from public.engagement_log where project_id = p_project;
  for e in select jsonb_array_elements(p_log) loop
    insert into public.engagement_log (project_id, profile_id, version, at, agent, reason, changes)
    values (p_project, p_profile, (e ->> 'version')::integer, (e ->> 'at')::timestamptz, e ->> 'agent', e ->> 'reason',
      coalesce(e -> 'changes', '[]'));
  end loop;
  return jsonb_build_object('status', 'ok', 'version', p_version);
end;
$$;
${move ? `
-- 4. One-off move of the existing datasets, checked record by record, then the old table goes.
do $$
declare
  r record;
  got jsonb;
begin
  for r in select * from public.engagement_tables loop
    perform engagement.put(r.profile_id, r.project_id, r.tbl, r.records);
    got := engagement.get(r.project_id, r.tbl);
    if got <> r.records then
      raise exception 'engagement move: % in project % does not read back the same', r.tbl, r.project_id;
    end if;
  end loop;
end;
$$;

drop table public.engagement_tables;
` : ''}`

writeFileSync(join(root, outPath), sql)
console.log(`wrote ${outPath}: ${names.length} tables${move ? ', with the move' : ''}`)
